const SANS = 'Liberation Sans'

const DISCLAIMER =
  'This report is generated by an AI screening tool and does not constitute a medical diagnosis. Results must be interpreted by a qualified ophthalmologist.'

const riskStyles: Record<RiskLevel, { label: string; color: string }> = {
  low: { label: 'Low risk', color: '#16A34A' },
  moderate: { label: 'Moderate risk', color: '#EA580C' },
  high: { label: 'High risk', color: '#DC2626' },
  inconclusive: { label: 'Inconclusive', color: '#6B7280' },
}

const qualityBadges: Record<QualityStatus, { label: string; color: string }> = {
  pending: { label: 'Quality check pending', color: MUTED },
  suitable: { label: 'Suitable for review', color: '#16A34A' },
  insufficient: { label: 'Poor quality', color: '#DC2626' },
}

const eyeTitles: Record<EyeLabel, string> = {
  right: 'OD (Right Eye)',
  left: 'OS (Left Eye)',
}

// Liberation Serif and Sans match Times and Helvetica in shape and width, but can also draw
// characters such as Ọ, ṣ or ≥, which appear in patient names and AI findings and which the
// built-in PDF fonts can't. These files are listed in next.config.mjs so they get deployed.
const fontPath = (file: string) => path.join(process.cwd(), 'lib/pdf/fonts', file)
Font.register({
  family: SERIF,
  fonts: [
    { src: fontPath('LiberationSerif-Regular.ttf'), fontWeight: 400 },
    { src: fontPath('LiberationSerif-Bold.ttf'), fontWeight: 700 },
  ],
})
Font.register({
  family: SANS,
  fonts: [
    { src: fontPath('LiberationSans-Regular.ttf'), fontWeight: 400 },
    { src: fontPath('LiberationSans-Bold.ttf'), fontWeight: 700 },
  ],
})
// Keep names and clinical terms whole rather than splitting them across lines.
Font.registerHyphenationCallback((word) => [word])

