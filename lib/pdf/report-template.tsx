export interface ReportEye {
  eye: EyeLabel
  // JPEG data URI. Null when there is no picture to show.
  imageDataUri: string | null
  // Null when no image was captured for this eye.
  quality: QualityStatus | null
}

export interface ReportData {
  reportId: string
  examinationDate: string | null
  reportDate: string | null
  examiner: string
  patient: Pick<Patient, 'name' | 'age' | 'phone'>
  symptoms: string | null
  eyes: ReportEye[]
  analysis: CompletedAnalysis | null
  clinicianNotes: string | null
  clinicianRecommendation: string | null
}

function Footer() {
  return (
    <View style={styles.footer} fixed>
      <View style={styles.footerRow}>
        <Text style={styles.footerCell}>Eagle Eye Tech Ltd — AI Retinal Screening</Text>
        <Text style={styles.footerCenter}>CONFIDENTIAL — For clinical use only</Text>
        <Text
          style={styles.footerRight}
          render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`}
        />
      </View>
      <Text>{DISCLAIMER}</Text>
    </View>
  )
}

function SectionLabel({ children }: { children: string }) {
  return (
    <Text style={styles.sectionLabel} minPresenceAhead={30}>
      {children}
    </Text>
  )
}

function MetaItem({ label, value }: { label: string; value: string }) {
  return (
    <View style={styles.metaItem}>
      <Text style={styles.caption}>{label}</Text>
      <Text style={styles.strong}>{value}</Text>
    </View>
  )
}

function PatientRow({ cells }: { cells: [string, string][] }) {
  return (
    <View style={styles.tableRow}>
      {cells.map(([label, value]) => [
        <Text key={`${label}-label`} style={styles.tableLabel}>
          {label}
        </Text>,
        <Text key={`${label}-value`} style={styles.tableValue}>
          {value}
        </Text>,
      ])}
    </View>
  )
}

function EyePanel({ eye }: { eye: ReportEye }) {
  const badge = eye.quality ? qualityBadges[eye.quality] : null
  return (
    <View style={styles.eye}>
      <Text style={styles.strong}>{eyeTitles[eye.eye]}</Text>
      {eye.imageDataUri ? (
        <View style={[styles.eyeFrame, styles.eyeImageFrame]}>
          <Image src={eye.imageDataUri} style={styles.eyeImage} />
        </View>
      ) : (
        <View style={[styles.eyeFrame, styles.eyePlaceholderFrame]}>
          <Text style={{ color: MUTED }}>{eye.quality ? 'Image unavailable' : 'Not captured'}</Text>
        </View>
      )}
      {badge ? (
        <Text style={[styles.badge, { color: badge.color, borderColor: badge.color }]}>{badge.label}</Text>
      ) : null}
    </View>
  )
}

function AnalysisSections({ analysis }: { analysis: CompletedAnalysis }) {
  const risk = riskStyles[analysis.risk_level]
  return (
    <>
      <View style={styles.section} wrap={false}>
        <SectionLabel>AI Screening Results</SectionLabel>
        <View style={styles.summary}>
          <View style={styles.summaryCell}>
            <Text style={styles.caption}>Risk level</Text>
            <Text style={[styles.risk, { backgroundColor: risk.color }]}>{risk.label}</Text>
          </View>
          <View style={[styles.summaryCell, styles.summaryDivider]}>
            <Text style={styles.caption}>CDR estimate</Text>
            <Text style={styles.summaryValue}>{analysis.cdr_estimate ?? 'Not available'}</Text>
          </View>
          <View style={[styles.summaryCell, styles.summaryDivider]}>
            <Text style={styles.caption}>Confidence</Text>
            <Text style={styles.summaryValue}>
              {analysis.confidence !== null ? `${Math.round(analysis.confidence * 100)}%` : 'Not available'}
            </Text>
          </View>
        </View>
        {analysis.analysis_failed ? (
          <Text style={{ marginTop: 6 }}>
            Analysis could not be completed for every image, so this result is incomplete.
          </Text>
        ) : null}
      </View>

      <View style={styles.section}>
        <SectionLabel>Detailed Findings</SectionLabel>
        {analysis.findings.length > 0 ? (
          analysis.findings.map((finding, index) => (
            <View key={index} style={styles.finding} wrap={false}>
              <Text style={styles.findingNumber}>{index + 1}.</Text>
              <Text style={styles.findingText}>{finding}</Text>
            </View>
          ))
        ) : (
          <Text>No findings recorded.</Text>
        )}
      </View>

      <View style={styles.section} wrap={false}>
        <SectionLabel>Clinical Recommendation</SectionLabel>
        <Text style={styles.box}>{analysis.recommendation ?? 'No recommendation available.'}</Text>
      </View>

      <View style={styles.section} wrap={false}>
        <SectionLabel>Image Quality Assessment</SectionLabel>
        <Text>
          {analysis.quality_notes ??
            (analysis.image_quality === 'insufficient'
              ? 'Image quality was insufficient for a full assessment.'
              : analysis.image_quality === 'suitable'
                ? 'Image quality was suitable for review.'
                : 'Image quality was not assessed.')}
        </Text>
      </View>
    </>
  )
}

function ReportDocument({ data }: { data: ReportData }) {
  const { patient } = data
  return (
    <Document title="AI-Assisted Retinal Screening Report" author="Eagle Eye Tech Ltd">
      <Page size="A4" style={styles.page}>
        <View style={styles.content}>
          <View style={styles.banner}>
            <Image src={LOGO_PATH} style={styles.logo} />
            <View>
              <Text style={styles.company}>EAGLE EYE TECH LTD</Text>
              <Text style={styles.subtitle}>AI-Assisted Retinal Screening Report</Text>
            </View>
          </View>

          <View style={styles.meta}>
            <MetaItem label="Report ID" value={data.reportId} />
            <MetaItem label="Date of examination" value={formatDate(data.examinationDate)} />
            <MetaItem label="Date of report" value={formatDate(data.reportDate)} />
            <MetaItem label="Status" value="Clinician reviewed" />
          </View>

          <View style={styles.section} wrap={false}>
            <SectionLabel>Patient Information</SectionLabel>
            <View style={styles.table}>
              <PatientRow
                cells={[
                  ['Name', patient.name],
                  ['Age', String(patient.age)],
                ]}
              />
              <PatientRow
                cells={[
                  ['Phone', patient.phone ?? '—'],
                  ['Examiner', data.examiner],
                ]}
              />
            </View>
          </View>

          <View style={styles.section}>
            <SectionLabel>Presenting Complaints</SectionLabel>
            <Text style={styles.box}>{data.symptoms ?? 'None recorded.'}</Text>
          </View>

          <View style={styles.section} wrap={false}>
            <SectionLabel>Retinal Images</SectionLabel>
            <View style={styles.eyes}>
              {data.eyes.map((eye) => (
                <EyePanel key={eye.eye} eye={eye} />
              ))}
            </View>
          </View>
        </View>
        <Footer />
      </Page>

      <Page size="A4" style={styles.page}>
        <View style={styles.content}>
          {data.analysis ? (
            <AnalysisSections analysis={data.analysis} />
          ) : (
            <View style={styles.section}>
              <SectionLabel>AI Screening Results</SectionLabel>
              <Text>AI analysis was not completed for this examination.</Text>
            </View>
          )}

          {data.clinicianNotes || data.clinicianRecommendation ? (
            <View style={styles.section} wrap={false}>
              <SectionLabel>Clinician Review</SectionLabel>
              {data.clinicianNotes ? (
                <Text>
                  <Text style={styles.strong}>Notes: </Text>
                  {data.clinicianNotes}
                </Text>
              ) : null}
              {data.clinicianRecommendation ? (
                <Text>
                  <Text style={styles.strong}>Recommendation: </Text>
                  {data.clinicianRecommendation}
                </Text>
              ) : null}
            </View>
          ) : null}
        </View>
        <Footer />
      </Page>
    </Document>
  )
}

export function renderReportPdf(data: ReportData) {
  return renderToBuffer(<ReportDocument data={data} />)
}
