import type { CompletedAnalysis } from '@/lib/ai-result'
import { formatDate } from '@/lib/format'
import type { EyeLabel, Patient, QualityStatus, RiskLevel } from '@/lib/supabase/types'

const ACCENT = '#7C3AED'
